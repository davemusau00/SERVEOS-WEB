export function renderCommandInventory(){
 const lines=['# SERVEOS API command registry inventory','','Generated from the registered business-command registries by `scripts/command-inventory.mjs`. Every operation below is authoritative, version-checked and executed inside the API transaction engine. Do not edit this file by hand; regenerate it.','','For each operation the registry declares: the permission that gates it, any alternative permission set, an approval permission where manager authorization applies, and the offline policy (`ONLINE_ONLY` commands must never be queued offline).',''];
 let total=0;
 for(const [title,registry] of groups){
  lines.push(`## ${title}`,'',`| Operation | Permission | Alternative permissions | Approval permission | Offline policy |`,'|---|---|---|---|---|');
  const rows=[...registry.entries()].sort((left,right)=>left[0].localeCompare(right[0]));
  for(const [operation,config] of rows){
   total++;
   lines.push(`| \`${operation}\` | ${config.permission?`\`${config.permission}\``:'—'} | ${(config.permissionAny??[]).map(item=>`\`${item}\``).join(' ')||'—'} | ${config.approvalPermission?`\`${config.approvalPermission}\``:'—'} | ${config.offlinePolicy??'ONLINE_ONLY'} |`);
  }
  lines.push('');
 }
 lines.push(`Total registered operations: ${total}.`,'');
 return lines.join('\n');
}

const generate=()=>{
 const markdown=renderCommandInventory();
 const target=resolve(here,'../docs/generated/command-registry.md');
 mkdirSync(dirname(target),{recursive:true});
 writeFileSync(target,markdown);
 console.log(`Wrote ${target} (${markdown.split('\n').length} lines)`);
};

if(process.argv[1]&&process.argv[1].endsWith('command-inventory.mjs'))generate();
